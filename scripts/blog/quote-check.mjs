const maxCombinations = 512;

/**
 * 把一段简体（或简繁混排）文字展开为所有可能的繁体候选。
 */
export function traditionalCandidates(text) {
  let candidates = [""];
  for (const character of Array.from(text)) {
    const options = ambiguous[character] ?? [unambiguous[character] ?? character];
    const next = [];
    for (const prefix of candidates) {
      for (const option of options) {
        next.push(prefix + option);
        if (next.length >= maxCombinations) break;
      }
      if (next.length >= maxCombinations) break;
    }
    candidates = next;
  }
  return candidates;
}

export function normalizeForMatch(text) {
  // 只保留 CJK 统一表意文字与扩展区；去掉所有标点、空白与注音。
  return text.replace(/[^\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\u{20000}-\u{2a6df}]/gu, "");
}

function cbetaFileForCanonId(canonId, root) {
  const match = /^([A-Z]+)0*(\d+)[A-Za-z]?$/.exec(canonId.trim());
  if (!match) return null;
  const [, collection, number] = match;
  const directory = resolve(root, cbetaDirectory);
  if (!existsSync(directory)) return null;
  const padded = number.padStart(4, "0");
  const pattern = new RegExp(`^${collection}\\d+n${padded}[A-Za-z]?\\.xml$`);
  const fileName = readdirSync(directory).find((name) => pattern.test(name));
  return fileName ? resolve(directory, fileName) : null;
}

function loadNormalizedText(filePath) {
  if (textCache.has(filePath)) return textCache.get(filePath);
  const xml = readFileSync(filePath, "utf8");
  const body = xml
    .replace(/<teiHeader\b[\s\S]*?<\/teiHeader>/g, "")
    .replace(/<note\b[\s\S]*?<\/note>/g, "")
    .replace(/<rdg\b[\s\S]*?<\/rdg>/g, "")
    .replace(/<[^>]+>/g, "");
  const normalized = normalizeForMatch(body);
  textCache.set(filePath, normalized);
  return normalized;
}

/**
 * 返回 { status: "verified" | "unverified", reason }。
 */
export function verifyQuote({ text, canonId }, root = process.cwd()) {
  const filePath = canonId ? cbetaFileForCanonId(canonId, root) : null;
  if (!filePath) return { status: "unverified", reason: `仓库内没有 ${canonId || "（未提供经号）"} 的受控 TEI 原文` };
  const needle = normalizeForMatch(text);
  if (Array.from(needle).length < 4) return { status: "unverified", reason: "引文太短，无法可靠核对" };
  const haystack = loadNormalizedText(filePath);
  const fileName = filePath.split("/").pop();
  for (const candidate of traditionalCandidates(needle)) {
    if (haystack.includes(candidate)) return { status: "verified", reason: `逐字匹配 ${fileName}` };
  }
  return { status: "unverified", reason: `在 ${fileName} 中找不到逐字匹配（已做简繁与标点归一）` };
}
