import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import {
  workCatalogLedgerSchema,
  workCatalogTargetShardBytes,
} from "../src/lib/corpus-work-catalog-paths.mjs";

const root = process.cwd();
const write = process.argv.includes("--write");
const folioIndexPath = resolve(root, "src/data/corpus-folio-index.generated.json");
const ledgerPath = resolve(root, "src/data/corpus-work-ledger.generated.json");
const chunksDir = resolve(root, "src/data/corpus-work-catalog-chunks");
const loadersPath = resolve(root, "src/lib/corpus-work-catalog-loaders.generated.ts");

function serialize(value) {
  return `${JSON.stringify(value)}\n`;
}

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function packWorks(works) {
  const items = Object.entries(works).map(([slug, work]) => ({
    slug,
    work,
    size: Buffer.byteLength(JSON.stringify(work)),
  }));
  items.sort((left, right) => right.size - left.size || compareText(left.slug, right.slug));

  const shards = [];
  let current = { works: {}, size: 0 };
  for (const item of items) {
    if (current.size > 0 && current.size + item.size > workCatalogTargetShardBytes) {
      shards.push(current);
      current = { works: {}, size: 0 };
    }
    current.works[item.slug] = item.work;
    current.size += item.size;
  }
  if (Object.keys(current.works).length > 0) shards.push(current);
  return shards;
}

function buildLoadersSource(shardCount) {
  const cases = Array.from({ length: shardCount }, (_, id) => {
    return `    case ${id}:\n      return ((await import("@/data/corpus-work-catalog-chunks/${id}.json")).default).works;`;
  }).join("\n");

  return `// Generated by scripts/build-corpus-work-catalog.mjs. Do not edit.
export async function loadWorkCatalogShardWorks(id: number): Promise<Record<string, unknown> | null> {
  switch (id) {
${cases}
    default:
      return null;
  }
}
`;
}

const folioIndex = JSON.parse(await readFile(folioIndexPath, "utf8"));
const works = folioIndex.works ?? {};
const slugs = Object.keys(works).sort(compareText);
if (slugs.length !== folioIndex.totalWorks) {
  throw new Error("版页索引 totalWorks 与 works 键数不一致");
}

const packed = packWorks(works);
const slugToShard = {};
for (const [id, shard] of packed.entries()) {
  for (const slug of Object.keys(shard.works)) slugToShard[slug] = id;
}

if (Object.keys(slugToShard).length !== slugs.length) {
  throw new Error("经目账本 slug 分片覆盖不完整");
}

const ledger = {
  schema: workCatalogLedgerSchema,
  workCount: slugs.length,
  folioCount: folioIndex.totalFolios,
  shardCount: packed.length,
  targetShardBytes: workCatalogTargetShardBytes,
  slugToShard,
};

const expectedLoaders = buildLoadersSource(packed.length);
const expectedLedger = serialize(ledger);
const expectedChunks = new Map(
  packed.map((shard, id) => [
    `${id}.json`,
    serialize({
      id,
      works: Object.fromEntries(
        Object.entries(shard.works).sort(([left], [right]) => compareText(left, right)),
      ),
    }),
  ]),
);

if (write) {
  await rm(chunksDir, { recursive: true, force: true });
  await mkdir(chunksDir, { recursive: true });
  await writeFile(ledgerPath, expectedLedger);
  for (const [name, body] of expectedChunks) {
    await writeFile(resolve(chunksDir, name), body);
  }
  await writeFile(loadersPath, expectedLoaders);
} else {
  const actualLedger = await readFile(ledgerPath, "utf8");
  if (actualLedger !== expectedLedger) {
    throw new Error("src/data/corpus-work-ledger.generated.json 与版页索引不一致；运行 pnpm build:corpus-work-catalog");
  }
  const actualLoaders = await readFile(loadersPath, "utf8");
  if (actualLoaders !== expectedLoaders) {
    throw new Error("src/lib/corpus-work-catalog-loaders.generated.ts 与经目分片不一致；运行 pnpm build:corpus-work-catalog");
  }
  const actualNames = new Set(await readdir(chunksDir));
  if (actualNames.size !== expectedChunks.size) {
    throw new Error("src/data/corpus-work-catalog-chunks 分片数量与账本不一致；运行 pnpm build:corpus-work-catalog");
  }
  for (const [name, body] of expectedChunks) {
    const actual = await readFile(resolve(chunksDir, name), "utf8");
    if (actual !== body) {
      throw new Error(`${name} 与预计算经目分片不一致；运行 pnpm build:corpus-work-catalog`);
    }
  }
}

console.log(
  `${write ? "已生成" : "已验证"} 经目账本：${ledger.workCount} 个文本、${ledger.folioCount} 个版页、${ledger.shardCount} 个分片。`,
);
