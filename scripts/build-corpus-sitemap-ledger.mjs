import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import {
  catalogSlugSources,
  sitemapChunkSize,
  sitemapLedgerSchema,
  sitemapLibraryPageSize,
  sitemapStaticPaths,
} from "../src/lib/sitemap-static-paths.mjs";

const root = process.cwd();
const write = process.argv.includes("--write");
const folioIndexPath = resolve(root, "src/data/corpus-folio-index.generated.json");
const ledgerPath = resolve(root, "src/data/corpus-sitemap-ledger.generated.json");
const chunksDir = resolve(root, "src/data/corpus-sitemap-chunks");
const loadersPath = resolve(root, "src/lib/sitemap-chunk-loaders.generated.ts");

function serialize(value) {
  return `${JSON.stringify(value)}\n`;
}

async function readCatalogSlugs() {
  const slugs = [];
  for (const relativePath of catalogSlugSources) {
    const catalog = JSON.parse(await readFile(resolve(root, relativePath), "utf8"));
    if (!Array.isArray(catalog.files)) {
      throw new Error(`${relativePath} 缺少 files 清单`);
    }
    for (const file of catalog.files) {
      if (!file?.slug) throw new Error(`${relativePath} 有条目缺少 slug`);
      slugs.push(file.slug);
    }
  }
  return slugs;
}

function buildLibraryPaginationPaths(workCount) {
  return Array.from(
    { length: Math.max(0, Math.ceil(workCount / sitemapLibraryPageSize) - 1) },
    (_, index) => `/jingzang/page/${index + 2}`,
  );
}

function buildLoadersSource(sitemapCount) {
  const cases = Array.from({ length: sitemapCount }, (_, id) => {
    return `    case ${id}:\n      return ((await import("@/data/corpus-sitemap-chunks/${id}.json")).default).paths;`;
  }).join("\n");

  return `// Generated by scripts/build-corpus-sitemap-ledger.mjs. Do not edit.
export async function loadSitemapChunkPaths(id: number): Promise<string[] | null> {
  switch (id) {
${cases}
    default:
      return null;
  }
}
`;
}

const folioIndex = JSON.parse(await readFile(folioIndexPath, "utf8"));
const slugs = await readCatalogSlugs();
const works = folioIndex.works ?? {};

const missingIndex = slugs.filter((slug) => !works[slug]?.navigation?.length);
if (missingIndex.length > 0) {
  throw new Error(`目录 slug 缺少版页索引：${missingIndex[0]}`);
}

const extraIndex = Object.keys(works).filter((slug) => !slugs.includes(slug));
if (extraIndex.length > 0) {
  throw new Error(`版页索引 slug 不在目录中：${extraIndex[0]}`);
}

const libraryPaginationPaths = buildLibraryPaginationPaths(slugs.length);
const workPaths = slugs.map((slug) => `/jingzang/${slug}`);
const folioPaths = slugs.flatMap((slug) =>
  works[slug].navigation.map((item) => `/jingzang/${slug}/${item.key}`),
);

const allPaths = [...sitemapStaticPaths, ...libraryPaginationPaths, ...workPaths, ...folioPaths];
const sitemapCount = Math.ceil(allPaths.length / sitemapChunkSize);
const chunks = Array.from({ length: sitemapCount }, (_, id) => ({
  id,
  paths: allPaths.slice(id * sitemapChunkSize, (id + 1) * sitemapChunkSize),
}));

const ledger = {
  schema: sitemapLedgerSchema,
  chunkSize: sitemapChunkSize,
  staticPathCount: sitemapStaticPaths.length,
  libraryPageCount: libraryPaginationPaths.length,
  workCount: slugs.length,
  folioCount: folioPaths.length,
  totalUrls: allPaths.length,
  sitemapCount,
};

const expectedLoaders = buildLoadersSource(sitemapCount);
const expectedLedger = serialize(ledger);
const expectedChunks = new Map(chunks.map((chunk) => [`${chunk.id}.json`, serialize({ id: chunk.id, paths: chunk.paths })]));

if (write) {
  await rm(chunksDir, { recursive: true, force: true });
  await mkdir(chunksDir, { recursive: true });
  await writeFile(ledgerPath, expectedLedger);
  for (const [name, body] of expectedChunks) {
    await writeFile(resolve(chunksDir, name), body);
  }
  await writeFile(loadersPath, expectedLoaders);
} else {
  const actualLedger = await readFile(ledgerPath, "utf8");
  if (actualLedger !== expectedLedger) {
    throw new Error("src/data/corpus-sitemap-ledger.generated.json 与目录/版页索引不一致；运行 pnpm build:corpus-sitemap-ledger");
  }
  const actualLoaders = await readFile(loadersPath, "utf8");
  if (actualLoaders !== expectedLoaders) {
    throw new Error("src/lib/sitemap-chunk-loaders.generated.ts 与 sitemap 分片不一致；运行 pnpm build:corpus-sitemap-ledger");
  }
  const actualNames = new Set(await readdir(chunksDir));
  if (actualNames.size !== expectedChunks.size) {
    throw new Error("src/data/corpus-sitemap-chunks 分片数量与账本不一致；运行 pnpm build:corpus-sitemap-ledger");
  }
  for (const [name, body] of expectedChunks) {
    const actual = await readFile(resolve(chunksDir, name), "utf8");
    if (actual !== body) {
      throw new Error(`${name} 与预计算 sitemap 路径不一致；运行 pnpm build:corpus-sitemap-ledger`);
    }
  }
}

console.log(
  `${write ? "已生成" : "已验证"} sitemap 账本：${ledger.totalUrls} 个 URL、${ledger.sitemapCount} 个分片、${ledger.folioCount} 个版页。`,
);
